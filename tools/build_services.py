#!/usr/bin/env python3
"""Generate the service detail pages and the chat's service list.

Source of truth: data/services.json
Writes:          services/<slug>.html  and  assets/js/services-data.js

Run from the repository root after editing the JSON:
    python3 tools/build_services.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
services = json.loads((ROOT / "data/services.json").read_text())
by_slug = {s["slug"]: s for s in services}

# Reuse the icon sprite from the home page so icons stay in one place.
index = (ROOT / "index.html").read_text()
sprite = re.search(r'<svg width="0" height="0".*?</svg>', index, re.S).group(0)

e = html.escape


def features(s):
    return "\n".join(
        f'''          <article class="kk-card tilt">
            <h3>{e(f["t"])}</h3>
            <p>{e(f["d"])}</p>
          </article>'''
        for f in s["features"]
    )


def steps(s):
    return "\n".join(
        f'''          <li class="stage">
            <p class="stage-num">{i + 1:02d}</p>
            <h3>{e(st["t"])}</h3>
            <p>{e(st["d"])}</p>
          </li>'''
        for i, st in enumerate(s["steps"])
    )


def faqs(s):
    return "\n".join(
        f'''          <details>
            <summary>{e(q["q"])}</summary>
            <p>{e(q["a"])}</p>
          </details>'''
        for q in s["faqs"]
    )


def related(s):
    out = []
    for slug in s["related"]:
        r = by_slug[slug]
        out.append(
            f'''          <a class="svc-related" href="{slug}.html">
            <div class="card-top"><svg class="card-icon"><use href="#{r["icon"]}"/></svg><span class="card-cat">{e(r["catLabel"])}</span></div>
            <h3>{e(r["name"])}</h3>
            <p>{e(r["short"])}</p>
            <span class="card-link">View service <span aria-hidden="true">→</span></span>
          </a>'''
        )
    return "\n".join(out)


def page(s):
    name = e(s["name"])
    good = "".join(f"<li>{e(g)}</li>" for g in s["goodFor"])
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{name} · Omni AI Builders</title>
<meta name="description" content="{e(s["short"])}">
<meta name="theme-color" content="#0A0F14">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400..800&family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&display=swap">
<link rel="stylesheet" href="../assets/css/styles.css">
</head>
<body data-page="service" data-service="{s["slug"]}">
<!-- Generated by tools/build_services.py from data/services.json. Edit the JSON, not this file. -->

<canvas id="scene" aria-hidden="true"></canvas>
<div class="agent-bubble" id="agent-bubble" aria-hidden="true"><span class="agent-name">Omni · Website helper</span><span id="agent-text"></span></div>
<div class="scrim" aria-hidden="true"></div>

{sprite}

<header class="nav">
  <div class="wrap nav-inner">
    <a class="brand" href="../index.html" aria-label="Omni AI Builders home">
      <span class="brand-mark" aria-hidden="true"></span>
      <span>Omni <span class="brand-sub">AI Builders</span></span>
    </a>
    <nav class="nav-links" aria-label="Primary">
      <a href="../index.html#services">Services</a>
      <a href="../index.html#who">Who we help</a>
      <a href="../index.html#process">Process</a>
      <a href="../index.html#calculator">Calculator</a>
      <a href="../index.html#faq">FAQ</a>
    </nav>
    <a class="btn btn-small" href="../index.html#contact" data-pick="{s["slug"]}">Book a call</a>
  </div>
  <div class="progress" aria-hidden="true"><span id="progress-bar"></span></div>
</header>
<div class="cursor" id="cursor" aria-hidden="true"></div>

<main id="top">
  <section class="hero svc-hero" data-agent="svc" data-agent-line="{e(s["agentLine"])}">
    <div class="wrap hero-inner">
      <div class="hero-copy">
        <nav class="crumbs" aria-label="Breadcrumb"><a href="../index.html#services">Services</a><span aria-hidden="true">/</span><span>{e(s["catLabel"])}</span></nav>
        <div class="svc-title"><svg class="card-icon"><use href="#{s["icon"]}"/></svg></div>
        <h1>{name}</h1>
        <p class="lede">{e(s["lede"])}</p>
        <div class="cta-row">
          <a class="btn" href="../index.html#contact" data-pick="{s["slug"]}">Book a call about this</a>
          <a class="btn btn-ghost" href="#included">See what's included</a>
        </div>
        <p class="trust">Includes: {e(s["includes"])}</p>
      </div>
    </div>
  </section>

  <section class="section" id="included" data-agent="svc-features" data-agent-line="These are the parts that do the heavy lifting.">
    <div class="wrap">
      <header class="section-head">
        <p class="eyebrow">What you get</p>
        <h2>Everything included in {name}.</h2>
      </header>
      <div class="kk-grid">
{features(s)}
      </div>
      <div class="svc-good">
        <h3>Great for</h3>
        <ul class="kk-features">{good}</ul>
      </div>
    </div>
  </section>

  <section class="section" id="how" data-agent="svc-steps" data-agent-line="Here's how we get you live, step by step.">
    <div class="wrap">
      <header class="section-head">
        <p class="eyebrow">How it works</p>
        <h2>From first call to live, in four steps.</h2>
      </header>
      <ol class="pipeline">
{steps(s)}
      </ol>
    </div>
  </section>

  <section class="section" id="faq" data-agent="faq" data-agent-line="Questions? These are the ones we hear most.">
    <div class="wrap faq">
      <header class="section-head">
        <p class="eyebrow">Questions</p>
        <h2>{name}, answered.</h2>
      </header>
      <div class="faq-list">
{faqs(s)}
      </div>
    </div>
  </section>

  <section class="section" id="related" aria-labelledby="related-title">
    <div class="wrap">
      <header class="section-head">
        <p class="eyebrow">Works well with</p>
        <h2 id="related-title">Related services</h2>
      </header>
      <div class="svc-related-grid">
{related(s)}
      </div>
    </div>
  </section>

  <section class="finale" data-agent="finale" data-agent-line="Shall we set this up for you?" aria-labelledby="finale-title">
    <div class="wrap finale-inner">
      <p class="eyebrow">{e(s["catLabel"])}</p>
      <h2 id="finale-title">Ready for {name}?</h2>
      <p class="section-sub">Book a free 30-minute strategy call. We'll show you how it would work for your business.</p>
      <div class="cta-row">
        <a class="btn" href="../index.html#contact" data-pick="{s["slug"]}">Book a free strategy call</a>
        <a class="btn btn-ghost" href="../index.html#services">See all services</a>
      </div>
    </div>
  </section>
</main>

<footer class="footer">
  <div class="wrap footer-inner">
    <a class="brand" href="../index.html"><span class="brand-mark" aria-hidden="true"></span><span>Omni <span class="brand-sub">AI Builders</span></span></a>
    <p>Automate whatever you want.</p>
    <p class="footer-legal">© <span id="year">2026</span> Omni AI Builders. All rights reserved.</p>
  </div>
</footer>

<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>
<script src="../assets/js/services-data.js"></script>
<script src="../assets/js/scene.js"></script>
<script src="../assets/js/main.js"></script>
<script src="../assets/js/chat.js"></script>
<!-- NextLevel AI chat widget (bottom-right; Omni sits bottom-left) -->
<script>
  window.company_id = '6ad1226beac9797ecadc5a60';
  var newScript = document.createElement('script');
  newScript.src = 'https://api.nextlevelai.site/widget/widget.js';
  document.getElementsByTagName('HEAD')[0].appendChild(newScript);
</script>
</body>
</html>
'''


(ROOT / "services").mkdir(exist_ok=True)
for s in services:
    (ROOT / "services" / f'{s["slug"]}.html').write_text(page(s))

# Compact list for the chat agent
chat_list = [
    {k: s[k] for k in ("slug", "name", "cat", "catLabel", "audience", "chatPain", "short")}
    for s in services
]
(ROOT / "assets/js/services-data.js").write_text(
    "/* Generated by tools/build_services.py from data/services.json. */\n"
    "window.OMNI_SERVICES = " + json.dumps(chat_list, indent=2, ensure_ascii=False) + ";\n"
)
print(f"Wrote {len(services)} service pages and assets/js/services-data.js")
